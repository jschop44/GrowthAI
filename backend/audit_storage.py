"""Opt-in durable audit storage. Existing SQLite remains unchanged until cutover."""
import os
from contextlib import contextmanager
from types import SimpleNamespace
import psycopg
from psycopg.rows import dict_row

SCHEMA_SQL = '''
CREATE SCHEMA IF NOT EXISTS growthlens_audit;
CREATE TABLE IF NOT EXISTS growthlens_audit.organizations (
 id BIGINT PRIMARY KEY, name TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS growthlens_audit.audits (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT REFERENCES growthlens_audit.organizations(id),
 url TEXT NOT NULL, created_at TEXT NOT NULL, status TEXT NOT NULL,
 score INTEGER, result_json TEXT, error TEXT
);
CREATE INDEX IF NOT EXISTS idx_growthlens_audits_created ON growthlens_audit.audits(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_growthlens_audits_url ON growthlens_audit.audits(url,id DESC);
'''
# Only the application's fixed, parameterized statements are accepted. Arbitrary
# SQL, identifiers and generic placeholder rewrites are deliberately unsupported.
QUERIES = {
 'INSERT INTO audits(url,created_at,status) VALUES(?,?,?)':
  'INSERT INTO growthlens_audit.audits(url,created_at,status) VALUES(%s,%s,%s) RETURNING id',
 'UPDATE audits SET status=?,score=?,result_json=? WHERE id=?':
  'UPDATE growthlens_audit.audits SET status=%s,score=%s,result_json=%s WHERE id=%s',
 'UPDATE audits SET status=?,error=? WHERE id=?':
  'UPDATE growthlens_audit.audits SET status=%s,error=%s WHERE id=%s',
 'SELECT id,url,created_at,status,score FROM audits ORDER BY id DESC LIMIT 50':
  'SELECT id,url,created_at,status,score FROM growthlens_audit.audits ORDER BY id DESC LIMIT 50',
 'SELECT * FROM audits WHERE id=?':
  'SELECT * FROM growthlens_audit.audits WHERE id=%s',
 'SELECT result_json FROM audits WHERE id=? AND status=?':
  'SELECT result_json FROM growthlens_audit.audits WHERE id=%s AND status=%s',
 'SELECT url FROM audits WHERE id=? AND status=?':
  'SELECT url FROM growthlens_audit.audits WHERE id=%s AND status=%s',
 'SELECT id,created_at,status,score,result_json FROM audits WHERE url=? ORDER BY id DESC LIMIT 1':
  'SELECT id,created_at,status,score,result_json FROM growthlens_audit.audits WHERE url=%s ORDER BY id DESC LIMIT 1',
}


def storage_mode():
    mode = os.getenv('GROWTHLENS_AUDIT_STORAGE', 'sqlite').strip().lower()
    if mode not in ('sqlite', 'postgres'):
        raise ValueError('GROWTHLENS_AUDIT_STORAGE must be sqlite or postgres')
    return mode


def database_url():
    value = (os.getenv('GROWTHLENS_AUDIT_DATABASE_URL', '').strip()
             or os.getenv('DATABASE_URL', '').strip() or os.getenv('NEON_DATABASE_URL', '').strip())
    if not value:
        raise RuntimeError('Durable audit storage requires a configured database connection')
    return value


class AuditConnection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, parameters=()):
        normalized = ' '.join(query.split())
        statement = QUERIES.get(normalized)
        if statement is None:
            raise ValueError('Unsupported audit storage statement')
        cursor = self.raw.execute(statement, parameters)
        if normalized.startswith('INSERT INTO audits('):
            return SimpleNamespace(lastrowid=cursor.fetchone()['id'])
        return cursor


@contextmanager
def postgres_database():
    # Transaction context commits successful work and rolls back every exception.
    # Never fall back to ephemeral SQLite after a PostgreSQL failure.
    with psycopg.connect(database_url(), connect_timeout=5, row_factory=dict_row,
                         application_name='growthlens-audits') as raw:
        # Transaction poolers can reject libpq's startup `options` parameter.
        # Keep the timeout transaction-local instead of changing pooled session state.
        raw.execute('SET LOCAL statement_timeout = 10000')
        yield AuditConnection(raw)


def initialize_postgres():
    with postgres_database() as connection:
        connection.raw.execute(SCHEMA_SQL)
